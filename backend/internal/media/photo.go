package media

const (
	// PhotoMaxBytes — сколько может весить загружаемая фотография.
	// Больше аватара: это то, ради чего приложение открывают, и
	// снимок с телефона легко весит несколько мегабайт.
	PhotoMaxBytes = 10 << 20
	// PhotoMaxSide — до какого размера уменьшается фотография поста.
	// При дачной связи это разница между «загрузилось» и «приложение
	// не работает» (specs/003-posts.md, требование 5).
	PhotoMaxSide = 1600
	// PhotoExt — расширение, с которым фотография сохраняется.
	PhotoExt = ".jpg"
	// PhotoDir — папка фотографий постов в хранилище.
	PhotoDir = "posts"
)

// NormalizePhoto приводит загруженную фотографию к виду, в котором она
// хранится, и возвращает вместе с ней размеры: их отдают клиенту, чтобы
// лента заняла место под картинку до того, как та загрузится.
func NormalizePhoto(raw []byte) (Image, error) {
	return Normalize(raw, PhotoMaxSide)
}
