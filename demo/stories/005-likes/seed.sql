-- Лайки расставлены так, чтобы в ленте были видны все состояния сразу:
-- пост без лайков, пост с одним, пост, который отметили все трое, и
-- посты, отмеченные самим Николаем (+79000000001) — он первый в списке
-- дачников, и входить на показе удобнее всего им.
INSERT INTO post_likes (post_id, user_id)
SELECT p.id, u.id
FROM generate_series(1, 24) AS i
JOIN posts p
	ON p.id = ('00000000-0000-4000-8000-' || lpad(i::text, 12, '0'))::uuid
CROSS JOIN LATERAL (VALUES
	('11111111-1111-4111-8111-111111111111'::uuid, 2),
	('22222222-2222-4222-8222-222222222222'::uuid, 3),
	('33333333-3333-4333-8333-333333333333'::uuid, 4)
) AS liker(id, every_nth)
JOIN users u ON u.id = liker.id
WHERE i % liker.every_nth = 0;
