-- Данные сценария «Лента».
--
-- Ленту надо увидеть полной: с чужими постами, с разным числом
-- фотографий и длиной больше одной страницы, иначе подгрузку при
-- прокрутке показать не на чем (specs/004-feed.md). Руками столько
-- не выложишь, поэтому посты кладутся сразу в базу.
--
-- Фотографии — заглушки из demo/seed/media, их раскладывает demo/seed.sh.
-- Ключи начинаются с demo/: настоящие фотографии постов лежат в posts/.

-- 24 поста: две страницы по 20 и ещё четыре. Авторы — постоянный состав
-- стенда (demo/seed/001-users.sql), по кругу. Время идёт назад от «сейчас»:
-- самый свежий пост окажется наверху ленты.
INSERT INTO posts (id, author_id, caption, created_at)
SELECT
	('00000000-0000-4000-8000-' || lpad(i::text, 12, '0'))::uuid,
	(ARRAY[
		'11111111-1111-4111-8111-111111111111',
		'22222222-2222-4222-8222-222222222222',
		'33333333-3333-4333-8333-333333333333'
	])[1 + (i % 3)]::uuid,
	(ARRAY[
		'Первая клубника в этом году',
		'Картошку окучил, спина отваливается',
		'',
		'Соседи говорят, такой малины у них не было лет десять',
		'Теплица пережила заморозки',
		'Яблони зацвели',
		'Вот что выросло на трёх сотках. Земля тут глинистая, поэтому две недели ушло на грядки, зато теперь всё принялось и поливать приходится реже, чем в прошлом году',
		'Кабачки. Опять кабачки'
	])[1 + (i % 8)],
	now() - (i * 3 || ' hours')::interval
FROM generate_series(1, 24) AS i;

-- От одной до четырёх фотографий на пост: в ленте видна первая и отметка
-- «1/4», остальные — на экране поста.
INSERT INTO media (author_id, post_id, position, kind, storage_key, width, height)
SELECT p.author_id, p.id, pos, 'photo', ph.key, ph.width, ph.height
FROM generate_series(1, 24) AS i
JOIN posts p
	ON p.id = ('00000000-0000-4000-8000-' || lpad(i::text, 12, '0'))::uuid
CROSS JOIN LATERAL generate_series(1, 1 + (i % 4)) AS pos
JOIN (VALUES
	(1, 'demo/dacha-1.jpg', 1600, 1200),
	(2, 'demo/dacha-2.jpg', 1200, 1600),
	(3, 'demo/dacha-3.jpg', 1600, 900),
	(4, 'demo/dacha-4.jpg', 1400, 1400),
	(5, 'demo/dacha-5.jpg', 900, 1600),
	(6, 'demo/dacha-6.jpg', 1600, 1067)
) AS ph(n, key, width, height)
	ON ph.n = 1 + ((i + pos) % 6);
