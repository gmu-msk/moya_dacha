-- Номер поста → идентификатор. Пост 1 — самый свежий, наверху ленты.
CREATE FUNCTION pg_temp.dacha_post(n int) RETURNS uuid
	LANGUAGE sql IMMUTABLE
	RETURN ('00000000-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid;

