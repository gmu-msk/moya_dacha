-- Лайки: у кого один, у кого десяток. Разговорчивые посты отмечают
-- чаще, объявление о перегное
-- и тыквы без подписи — никто: в ленте видны и пустые сердечки.
-- Николай (+79000000001), которым удобнее всего входить на показе,
-- отметил часть постов сам. Своих постов никто не лайкает.
INSERT INTO post_likes (post_id, user_id, created_at)
SELECT p.id, u.id, p.created_at + make_interval(mins => u.n * 3)
FROM generate_series(1, 60) AS g(post)
JOIN posts p ON p.id = pg_temp.dacha_post(g.post)
JOIN dacha_users u ON u.id <> p.author_id
WHERE (g.post * 37 + u.n * 53) % 100 < CASE
	WHEN g.post IN (2, 33) THEN 0
	WHEN g.post IN (3, 6, 12, 14, 25) THEN 75
	ELSE 5 + (g.post * 29) % 55
END
AND p.created_at + make_interval(mins => u.n * 3) < now();

