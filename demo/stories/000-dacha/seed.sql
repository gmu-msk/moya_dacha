-- полдня назад: всё, что пришло к его малине, у него «Новое», и на
-- колокольчике горит точка.
UPDATE users SET notifications_seen_at = now() - interval '12 hours'
WHERE id = (SELECT id FROM dacha_users WHERE n = 1);
