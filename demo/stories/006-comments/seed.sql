-- Данные сценария «Комментарии».
--
-- Разговор показывают на посте, а дойти до поста надо из ленты, поэтому
-- берутся данные сценария лайков — они же тянут за собой посты ленты.
-- Файл лежит там, куда demo/seed.sh монтирует папку сценариев, и
-- применяется тем же psql (demo/stories/README.md).
\i /stories/005-likes/seed.sql

-- Комментарии расставлены так, чтобы в ленте сразу были видны все
-- состояния: пост без единого комментария, пост с одним и пост, под
-- которым разговор на несколько реплик. Время идёт вперёд внутри поста:
-- разговор читается сверху вниз (specs/006-comments.md, требование 5).
INSERT INTO comments (post_id, author_id, text, created_at)
SELECT
	('00000000-0000-4000-8000-' || lpad(c.post::text, 12, '0'))::uuid,
	c.author::uuid,
	c.text,
	now() - (c.post * 3 || ' hours')::interval + (c.minutes || ' minutes')::interval
FROM (VALUES
	-- Свежий пост наверху ленты: под ним разговор, и последнее слово
	-- не за Николаем — есть куда ответить.
	(1, '22222222-2222-4222-8222-222222222222', 'Красота! Чем подкармливали?', 10),
	(1, '11111111-1111-4111-8111-111111111111', 'Да ничем особенным, зола да перегной', 25),
	(1, '33333333-3333-4333-8333-333333333333', 'У нас в этом году одни листья, завидую', 40),
	-- Пост с одним комментарием: видно, что и один — это уже разговор.
	(2, '11111111-1111-4111-8111-111111111111', 'Спина заживёт, картошка останется', 30),
	-- Николай уже отвечал сам: на показе входят им, и свои реплики
	-- должны быть видны рядом с чужими.
	(4, '11111111-1111-4111-8111-111111111111', 'Малина в этом году и правда удалась', 15),
	(4, '22222222-2222-4222-8222-222222222222', 'Дадите пару корешков осенью?', 55),
	(5, '11111111-1111-4111-8111-111111111111', 'Плёнку менял в мае, держит', 20)
	-- Пост 3 намеренно остаётся без комментариев.
) AS c(post, author, text, minutes);
